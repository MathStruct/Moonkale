import { chromium } from "playwright";
import assert from "node:assert/strict";

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1200, height: 1000 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
try {
  await page.goto(`http://127.0.0.1:${process.env.PORT ?? "8099"}/`, { waitUntil: "networkidle" });
  await page.click("#layout-document");
  const original = await page.locator(".canonical").textContent();
  await page.click("#layout-mixed");
  const viewport = page.locator(".primary .mk-editor-core-viewport");
  await page.waitForFunction(() => document.querySelector('.primary [data-line="1"]')?.getBoundingClientRect().height === 66);
  assert.equal(await page.locator(".primary .mk-layout-fixture-block").evaluate(el => el.getBoundingClientRect().height), 110);
  await page.locator(".primary .mk-layout-fixture-block").evaluate(el => { el.style.height = "143px"; });
  await page.waitForFunction(() => {
    const a = document.querySelector('.primary [data-line="0"]')?.getBoundingClientRect();
    const b = document.querySelector('.primary [data-line="2"]')?.getBoundingClientRect();
    return a && b && b.y - a.y === 231;
  });
  await page.locator(".primary .mk-layout-fixture-block").evaluate(el => { el.style.height = "110px"; });
  await page.waitForFunction(() => {
    const a = document.querySelector('.primary [data-line="0"]')?.getBoundingClientRect();
    const b = document.querySelector('.primary [data-line="2"]')?.getBoundingClientRect();
    return a && b && b.y - a.y === 198;
  });
  const row0 = await page.locator('.primary [data-line="0"]').boundingBox();
  const row2 = await page.locator('.primary [data-line="2"]').boundingBox();
  assert.equal(row2.y - row0.y, 198);
  await viewport.evaluate(el => { el.scrollTop = 2207; });
  await page.waitForFunction(() => document.querySelector(".primary .mk-native-surface")?.dataset.firstRow === "93");
  await page.click("#layout-taller");
  await page.waitForFunction(() => Math.abs(document.querySelector(".primary .mk-editor-core-viewport").scrollTop - 2273) < .5);
  assert.equal(await page.locator(".primary .mk-native-surface").getAttribute("data-first-row"), "93");
  await page.click("#mount");
  await page.locator(".primary [data-editor=rust]").waitFor({ state: "detached" });
  await page.click("#mount");
  await page.waitForFunction(() => document.querySelector(".primary .mk-native-surface")?.dataset.firstRow === "93");
  await page.waitForFunction(() => Math.abs(document.querySelector(".primary .mk-editor-core-viewport").scrollTop - 2273) < .5);
  await page.click("#reveal");
  await page.waitForFunction(() => document.querySelector(".primary .mk-native-surface")?.dataset.firstRow === "0");
  await page.locator(".primary .mk-layout-fixture-block").click();
  await page.keyboard.insertText("Q");
  await page.waitForFunction(expected => document.querySelector(".canonical")?.textContent === expected, original.replace("// row 1", "Q// row 1"));
  await page.keyboard.press("Control+z");
  await page.waitForFunction(expected => document.querySelector(".canonical")?.textContent === expected, original);
  await page.locator(".primary").evaluate(el => { el.style.height = "300px"; });
  await viewport.evaluate(el => { el.scrollTop = 3000; });
  await page.locator(".primary .mk-editor-core-input-sink").focus();
  await page.keyboard.press("Control+End");
  await page.keyboard.insertText("tail");
  await page.waitForFunction(expected => document.querySelector(".canonical")?.textContent === expected, original + "tail");
  await page.click("#layout-uniform");
  await viewport.evaluate(el => { el.scrollTop = 0; });
  await page.waitForFunction(() => document.querySelector('.primary [data-line="1"]')?.getBoundingClientRect().height === 22);
  assert.equal(await page.locator(".primary .mk-layout-fixture-block").count(), 0);
  await page.click("#folds");
  await page.click("#layout-mixed");
  await page.click("#fold-all");
  await page.waitForFunction(() => !document.querySelector(".primary .mk-layout-fixture-block"));
  assert.equal(await page.locator('.primary [data-line="0"]').evaluate(el => el.getBoundingClientRect().height), 22);
  await page.click("#unfold-all");
  await page.locator(".primary .mk-layout-fixture-block").waitFor();
  await page.click("#layout-uniform");
  await page.click("#layout-wrapped-document");
  await page.locator(".primary").evaluate(el => { el.style.width = "700px"; });
  await page.waitForTimeout(800);
  await viewport.evaluate(el => { el.scrollTop = 2207; });
  await page.waitForTimeout(200);
  const sourceLine = await page.locator(".primary .mk-editor-core-row").first().getAttribute("data-line");
  await page.locator(".primary").evaluate(el => { el.style.width = "400px"; });
  await page.waitForTimeout(900);
  assert.equal(await page.locator(".primary .mk-editor-core-row").first().getAttribute("data-line"), sourceLine);
  await page.locator(".primary").evaluate(el => { el.style.width = "700px"; });
  await page.waitForTimeout(900);
  assert.equal(await page.locator(".primary .mk-editor-core-row").first().getAttribute("data-line"), sourceLine);
  await page.click("#layout-document");
  await page.click("#layout-mixed");
  await viewport.evaluate(el => { el.scrollTop = 0; });
  await page.locator(".primary .mk-layout-fixture-block").waitFor();
  await page.click("#layout-delay");
  await page.locator(".primary .mk-layout-fixture-block").evaluate(el => { el.style.height = "999px"; });
  await page.waitForTimeout(80);
  await page.click("#layout-uniform");
  await page.click("#layout-mixed");
  await page.waitForTimeout(600);
  assert.equal(await page.locator('.primary [data-line="1"]').evaluate(el => el.getBoundingClientRect().height), 66);
  assert.equal(await page.locator(".primary .mk-layout-fixture-block").evaluate(el => el.getBoundingClientRect().height), 110);
  await page.click("#layout-uniform");
  await page.click('[data-language-fixture="nested.jl"]');
  await page.locator(".language .mk-editor-core-row").first().waitFor();
  await page.click('[data-language-fixture="nested.lean"]');
  await page.locator('.language [data-fold-line="3"]').click();
  await page.waitForFunction(() => !document.querySelector('.language [data-line="4"]'));
  await page.locator('.language [data-line="5"]').waitFor();
  assert.equal(await page.locator('.language [data-line="5"]').evaluate(el => el.getBoundingClientRect().height), 22);
  assert.deepEqual(errors, []);
  console.log("PASS: mixed-height scrolling, height-change anchor, remount, reveal, widget input, undo, resized tail, uniform reset, folding, DOM measurements, stale results and rewrap");
} finally {
  await browser.close();
}
