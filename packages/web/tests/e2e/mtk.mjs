// ADR-0020's first consumer: the ModelingToolkit library — an RC low-pass
// built in the panel from acausal pins (the capacitor's negative pin carries
// two wires: the return and the ground, a bus), generated as circuit.jl and
// compared byte-exact against the golden generation, and — when a Julia
// environment with ModelingToolkit exists (MTK_ENV, default the e2e cache's
// julia-mtk project) — simulated: the capacitor reads 1 - e^-5 = 99.3 % of
// the source after five time constants (τ = R·C = 1s, tspan (0, 5)).
import { chromium } from "playwright";
import fs from "node:fs";
import { spawnSync } from "node:child_process";
const S = process.env.M1_SHOTS ?? ".";
const PORT = process.env.PORT ?? 8080;
const ROOT = process.env.M1_ROOT;
const MTK_ENV = process.env.MTK_ENV ?? `${process.env.HOME}/.cache/moonkale-e2e/julia-mtk`;
// The golden generation: deterministic — @named names are sequential per
// kind in palette order, nets appear in wire order, and the uuid-suffixed
// block ids never reach the file.
const GOLDEN_RC = `# Generated by Moonkale's ModelingToolkit library — a .flow.json's circuit.
# Run: julia circuit.jl (needs ModelingToolkit, its StandardLibrary and OrdinaryDiffEq).
using ModelingToolkit
using ModelingToolkitStandardLibrary.Electrical
using ModelingToolkitStandardLibrary.Mechanical
using ModelingToolkitStandardLibrary.Blocks
using OrdinaryDiffEq

@independent_variables t

@named voltage_1_level = Blocks.Constant(k = 1.0)
@named voltage_1 = Voltage()
@named resistor_1 = Resistor(R = 1.0)
@named capacitor_1 = Capacitor(C = 1.0)
@named ground_1 = Ground()

@named circuit = ODESystem([
    connect(voltage_1.V, voltage_1_level.output),
    connect(voltage_1.p, resistor_1.p),
    connect(resistor_1.n, capacitor_1.p),
    connect(capacitor_1.n, voltage_1.n, ground_1.g),
], t; systems = [voltage_1, voltage_1_level, resistor_1, capacitor_1, ground_1])
circuit = structural_simplify(circuit)

prob = ODEProblem(circuit, [capacitor_1.v => 0.0], (0.0, 5.0))
sol = solve(prob, Tsit5())
println("capacitor_1.v at t=5.0: ", sol(5.0; idxs = capacitor_1.v))
`;
// The mixed circuit (RC + spring-mass): the mechanical half's golden.
const GOLDEN_MIXED = `# Generated by Moonkale's ModelingToolkit library — a .flow.json's circuit.
# Run: julia circuit.jl (needs ModelingToolkit, its StandardLibrary and OrdinaryDiffEq).
using ModelingToolkit
using ModelingToolkitStandardLibrary.Electrical
using ModelingToolkitStandardLibrary.Mechanical.Translational
using ModelingToolkitStandardLibrary.Blocks
using OrdinaryDiffEq

@independent_variables t

@named voltage_1_level = Blocks.Constant(k = 1.0)
@named voltage_1 = Voltage()
@named resistor_1 = Resistor(R = 1.0)
@named capacitor_1 = Capacitor(C = 1.0)
@named ground_1 = Ground()
@named fixed_1 = Fixed()
@named spring_1 = Spring(k = 100.0)
@named mass_1 = Mass(m = 1.0)

@named circuit = ODESystem([
    connect(voltage_1.V, voltage_1_level.output),
    connect(voltage_1.p, resistor_1.p),
    connect(resistor_1.n, capacitor_1.p),
    connect(capacitor_1.n, voltage_1.n, ground_1.g),
    connect(fixed_1.flange, spring_1.flange_a),
    connect(spring_1.flange_b, mass_1.flange),
], t; systems = [voltage_1, voltage_1_level, resistor_1, capacitor_1, ground_1, fixed_1, spring_1, mass_1])
circuit = structural_simplify(circuit)

prob = ODEProblem(circuit, [capacitor_1.v => 0.0, spring_1.delta_s => 0.1, mass_1.s => 0.1, mass_1.v => 0.0], (0.0, 5.0))
sol = solve(prob, Tsit5())
println("capacitor_1.v at t=0.5: ", sol(0.5; idxs = capacitor_1.v))
println("capacitor_1.v at t=1.0: ", sol(1.0; idxs = capacitor_1.v))
println("capacitor_1.v at t=5.0: ", sol(5.0; idxs = capacitor_1.v))
println("mass_1.s at t=0.5: ", sol(0.5; idxs = mass_1.s))
println("mass_1.s at t=1.0: ", sol(1.0; idxs = mass_1.s))
println("mass_1.s at t=5.0: ", sol(5.0; idxs = mass_1.s))
println("mass_1.v at t=0.5: ", sol(0.5; idxs = mass_1.v))
println("mass_1.v at t=1.0: ", sol(1.0; idxs = mass_1.v))
println("mass_1.v at t=5.0: ", sol(5.0; idxs = mass_1.v))
`;
const browser = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--ignore-gpu-blocklist"] });
const page = await browser.newPage({ viewport: { width: 1500, height: 900 } });
const logs = [];
page.on("console", (m) => { const t = m.text(); if (!t.includes("session[")) logs.push(`[${m.type()}] ${t.slice(0, 300)}`); });
const step = async (n, f) => { process.stdout.write(`- ${n} … `); await f(); console.log("ok"); };
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const status = () => page.$eval(".mk-flow-status:visible", (e) => ({ blocks: +e.dataset.blocks, wires: +e.dataset.wires, issues: +e.dataset.issues }));
const canvasRect = () => page.$eval(".mk-flow-canvas:visible", (e) => { const r = e.getBoundingClientRect(); return { x: r.left, y: r.top }; });
const positions = () => page.evaluate(() => Object.values(window.moonkale.flowViews)[0].node_positions());
const screenOf = (id) => page.evaluate((id) => Object.values(window.moonkale.flowViews)[0].node_screen_position(id), id);
const portOf = (id, port) => page.evaluate(({ id, port }) => Object.values(window.moonkale.flowViews)[0].port_screen_position(id, port), { id, port });
const idOfKind = async (prefix) => {
  const pos = JSON.parse(await positions());
  const id = Object.keys(pos).find((k) => k.toLowerCase().startsWith(prefix.toLowerCase() + "-"));
  if (!id) throw new Error(`no block of kind ${prefix}`);
  return id;
};
const dragPin = async (fromId, fromPort, toId, toPort) => {
  const box = await canvasRect();
  const a = await portOf(fromId, fromPort);
  const b = await portOf(toId, toPort);
  if (!a || !b) throw new Error(`pins not found for ${fromId}.${fromPort} → ${toId}.${toPort}`);
  await page.mouse.move(box.x + a[0], box.y + a[1]);
  await page.mouse.down();
  await page.mouse.move(box.x + b[0], box.y + b[1], { steps: 20 });
  await sleep(120);
  await page.mouse.up();
  await sleep(300);
};
try {
  await step("open folder; the ModelingToolkit library is off by default", async () => {
    await page.goto(`http://127.0.0.1:${PORT}/`, { waitUntil: "networkidle" });
    await page.waitForSelector(".wb-workspace");
    await page.click(".mk-explorer-open button[type=submit]");
    await page.waitForFunction(() => document.querySelector(".wb-status-bar").textContent.includes("index:"), null, { timeout: 30000 });
  });
  await step("Extensions panel: enable Flow editor and the ModelingToolkit library (Lux stays off — one library per flow)", async () => {
    await page.click("#mk-rail-extensions");
    await page.waitForSelector(".mk-settings-ext", { timeout: 10000 });
    await page.click(".mk-settings-ext:has(.mk-settings-ext-name:text-is('Flow editor')) > label input");
    await page.click(".mk-settings-ext:has(.mk-settings-ext-name:text-is('ModelingToolkit library')) > label input");
    await page.waitForFunction(() => /editor-flow/.test(localStorage.getItem("moonkale.settings") || "") && /ext-mtk/.test(localStorage.getItem("moonkale.settings") || ""), null, { timeout: 10000 });
  });
  await step("File → New Flow…; the palette offers the acausal components", async () => {
    await page.click(".mk-menu-button:has-text('File')");
    await page.click(".mk-menu-item:has-text('New Flow')");
    await page.waitForSelector(".mk-flow", { timeout: 15000 });
    await page.waitForSelector(".mk-flow-palette-block", { timeout: 10000 });
    const names = await page.$$eval(".mk-flow-palette-block", (els) => els.map((e) => e.textContent));
    for (const want of ["Voltage", "Resistor", "Capacitor", "Ground", "Mass", "Spring", "Damper", "Fixed"])
      if (!names.includes(want)) throw new Error(`${want} missing from the palette: ${names}`);
  });
  await step("place Voltage, Resistor, Capacitor, Ground; the unwired pins are issues", async () => {
    for (const b of ["Voltage", "Resistor", "Capacitor", "Ground"]) {
      await page.click(`.mk-flow-palette-block:text-is('${b}')`);
    }
    await page.waitForFunction(() => document.querySelector(".mk-flow-status")?.dataset.blocks === "4", null, { timeout: 10000 });
    const s = await status();
    if (s.issues === 0) throw new Error("seven unwired pins should be issues");
    console.log(`\n  status: ${JSON.stringify(s)}`);
  });
  await step("set C = 1.0 F (τ = R·C = 1s) in the floating parameter editor", async () => {
    const cap = await idOfKind("Capacitor");
    const box = await canvasRect();
    const p = await screenOf(cap);
    await page.mouse.click(box.x + p[0], box.y + p[1]);
    await page.waitForSelector(".mk-flow-props", { timeout: 10000 });
    const field = page.locator(".mk-flow-props .mk-flow-param:has-text('C') input");
    await field.click();
    await field.fill("1.0");
    await page.keyboard.press("Enter");
    await sleep(300);
    await page.mouse.click(box.x + 6, box.y + 6); // deselect: the editor leaves
    await sleep(200);
  });
  await step("wire the pins: three nets, the ground rides the capacitor's negative pin (a bus)", async () => {
    const v = await idOfKind("Voltage"), r = await idOfKind("Resistor"), c = await idOfKind("Capacitor"), g = await idOfKind("Ground");
    await dragPin(v, "p", r, "p");
    await dragPin(r, "n", c, "p");
    await dragPin(c, "n", v, "n");
    await dragPin(c, "n", g, "g"); // the second wire on c.n: one connect with all ends
    const s = await status();
    console.log(`\n  status: ${JSON.stringify(s)}`);
    if (s.wires !== 4 || s.issues !== 0) throw new Error("the RC is not wired cleanly");
    await page.screenshot({ path: `${S}/mtk-rc.png` });
  });
  await step("a wire between domains is refused (an electrical pin onto a mechanical flange)", async () => {
    await page.click(".mk-flow-palette-block:text-is('Mass')");
    await sleep(300);
    const m = await idOfKind("Mass"), r = await idOfKind("Resistor");
    await dragPin(r, "p", m, "flange");
    const s = await status();
    const notice = await page.$eval(".mk-flow .mk-flow-notice", (e) => e.textContent).catch(() => "");
    console.log(`\n  refused: ${notice.slice(0, 70)}`);
    if (s.wires !== 4) throw new Error("the cross-domain wire was accepted");
    if (!/does not connect/.test(notice)) throw new Error(`no refusal notice: "${notice}"`);
  });
  await step("Generate writes circuit.jl — byte-exact against the golden", async () => {
    // Delete the mass again (its block is the last added; select and Delete).
    const box = await canvasRect();
    const m = await idOfKind("Mass");
    const p = await screenOf(m);
    await page.mouse.click(box.x + p[0], box.y + p[1]);
    await sleep(200);
    await page.keyboard.press("Delete");
    await sleep(300);
    const s = await status();
    if (+s.blocks !== 4) throw new Error("the mass is still there: " + JSON.stringify(s));
    const btn = await page.$$(".mk-flow-generate");
    if (btn.length !== 1) throw new Error(`expected one generator, found ${btn.length}`);
    const label = await btn[0].textContent();
    if (!/ModelingToolkit/.test(label)) throw new Error(`the button does not name the library: ${label}`);
    await btn[0].click();
    await page.waitForFunction(() => /circuit\.jl/.test(document.querySelector(".mk-titlebar-title")?.textContent || ""), null, { timeout: 15000 });
    const generated = fs.readFileSync(`${ROOT}/circuit.jl`, "utf8");
    if (generated !== GOLDEN_RC) {
      console.log("\n  expected vs generated:");
      const a = GOLDEN_RC.split("\n"), b = generated.split("\n");
      for (let i = 0; i < Math.max(a.length, b.length); i++) if (a[i] !== b[i]) console.log(`  ${i}: ${JSON.stringify(a[i])}\n  ${i}: ${JSON.stringify(b[i])}`);
      throw new Error("the generated circuit.jl differs from the golden");
    }
  });
  await step("the mechanical half: a spring-mass released from s0 = 0.1 m beside the RC", async () => {
    for (const b of ["Fixed", "Spring", "Mass"]) {
      await page.click(`.mk-flow-palette-block:text-is('${b}')`);
    }
    await page.waitForFunction(() => document.querySelector(".mk-flow-status")?.dataset.blocks === "7", null, { timeout: 10000 });
    // Both initial conditions: the spring's elongation and the mass's
    // position must agree, or MTK leaves the system still.
    const setS0 = async (label, value) => {
      const box = await canvasRect();
      const id = await idOfKind(label);
      const p = await screenOf(id);
      await page.mouse.click(box.x + p[0], box.y + p[1]);
      await page.waitForSelector(".mk-flow-props", { timeout: 10000 });
      const field = page.locator(`.mk-flow-props .mk-flow-param:has-text('s0') input`);
      await field.click();
      await field.fill(value);
      await page.keyboard.press("Enter");
      await sleep(300);
      await page.mouse.click(box.x + 6, box.y + 6);
      await sleep(200);
    };
    await setS0("Spring", "0.1");
    await setS0("Mass", "0.1");
    const wall = await idOfKind("Fixed"), spr = await idOfKind("Spring"), ms = await idOfKind("Mass");
    await dragPin(wall, "flange", spr, "flange_a");
    await dragPin(spr, "flange_b", ms, "flange");
    const s = await status();
    console.log(`\n  status: ${JSON.stringify(s)}`);
    if (s.wires !== 6 || s.issues !== 0) throw new Error("the mixed circuit is not wired cleanly");
    await page.screenshot({ path: `${S}/mtk-mixed.png` });
  });
  await step("Generate again — the mixed circuit, byte-exact against its golden", async () => {
    const btn = await page.$$(".mk-flow-generate");
    await btn[0].click();
    await page.waitForTimeout(600); // circuit.jl is already open; the write is the event
    const generated = fs.readFileSync(`${ROOT}/circuit.jl`, "utf8");
    if (generated !== GOLDEN_MIXED) {
      const a = GOLDEN_MIXED.split("\n"), b = generated.split("\n");
      for (let i = 0; i < Math.max(a.length, b.length); i++) if (a[i] !== b[i]) console.log(`  ${i}: ${JSON.stringify(a[i])}\n  ${i}: ${JSON.stringify(b[i])}`);
      throw new Error("the generated mixed circuit.jl differs from the golden");
    }
  });
  await step("simulate: the capacitor charges to 99.3 % and the mass oscillates (skipped without a ModelingToolkit env)", async () => {
    if (!fs.existsSync(`${MTK_ENV}/Project.toml`)) {
      console.log(`\n  skipped: no ModelingToolkit environment at ${MTK_ENV} (julia --project=${MTK_ENV} with ModelingToolkit, its StandardLibrary and OrdinaryDiffEq)`);
      return;
    }
    const res = spawnSync("julia", [`--project=${MTK_ENV}`, `${ROOT}/circuit.jl`], { timeout: 280000, encoding: "utf8" });
    if (res.status !== 0) throw new Error(`julia failed: ${(res.stderr || "").slice(0, 400)}`);
    const cap = /capacitor_1\.v at t=5\.0: ([0-9.eE+-]+)/.exec(res.stdout);
    if (!cap) throw new Error(`no capacitor voltage in the output: ${res.stdout.slice(0, 200)}`);
    const v = parseFloat(cap[1]);
    const vs = [...res.stdout.matchAll(/mass_1\.v at t=([0-9.]+): (-?[0-9.eE+-]+)/g)].map((m) => parseFloat(m[2]));
    console.log(`\n  capacitor_1.v at t=5.0: ${v}  |  mass_1.v samples: ${vs.map((x) => x.toFixed(3)).join(", ")}`);
    if (v < 0.98 || v > 1.0) throw new Error(`the capacitor did not charge to 99 % (got ${v})`);
    if (!vs.some((x) => Math.abs(x) > 0.5)) throw new Error(`the mass did not oscillate (samples ${vs})`);
  });
  console.log("\nMTK E2E: PASS");
} catch (e) {
  console.log("\nFAIL:", e.message);
  await page.screenshot({ path: `${S}/mtk-fail.png` }).catch(() => {});
  console.log(logs.filter((l) => !/WARN|Copy Value/.test(l)).slice(-15).join("\n"));
  process.exitCode = 1;
} finally {
  await browser.close();
}
