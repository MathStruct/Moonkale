import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser = await chromium.launch();
const page = await browser.newPage({viewport:{width:1200,height:1000}});
const errors=[]; page.on('pageerror', error=>errors.push(error.message));
try {
  await page.goto(`http://127.0.0.1:${process.env.PORT??8099}/`,{waitUntil:'networkidle'});
  await page.click('#layout-document');
  const original=await page.locator('.canonical').textContent();
  await page.click('#layout-proportional');
  const ready=()=>page.waitForFunction(()=>document.querySelector('.primary .mk-proportional-run')?.dataset.ready==='true');
  await ready();
  assert.equal(await page.locator('.primary .mk-proportional-text').textContent(),original.split('\n')[0]);
  await page.waitForFunction(()=>document.querySelector('.primary [data-line="0"]').getBoundingClientRect().height===32);
  const cell=await page.locator('.primary .mk-proportional-text span').first().boundingBox();
  await page.mouse.click(cell.x+cell.width*.2,cell.y+cell.height/2);
  await page.keyboard.insertText('Q');
  await page.waitForFunction(expected=>document.querySelector('.canonical').textContent===expected,'Q'+original);
  await page.keyboard.press('Control+z');
  await page.waitForFunction(expected=>document.querySelector('.canonical').textContent===expected,original);
  await ready();
  await page.locator('.primary .mk-editor-core-input-sink').focus();
  await page.keyboard.press('Control+f');
  await page.locator('.primary .mk-search-query').fill('😀');
  await page.locator('.primary .mk-proportional-text .mk-native-search-match').waitFor();
  await ready();
  assert.equal(await page.locator('.canonical').textContent(),original);
  await page.locator('.primary .mk-search-query').press('Escape');
  const viewport=page.locator('.primary .mk-editor-core-viewport');
  await viewport.evaluate(el=>el.scrollTop=2000);
  await page.waitForFunction(()=>Number(document.querySelector('.primary .mk-native-surface').dataset.firstRow)>50);
  assert.ok(await page.locator('.primary .mk-editor-core-row').count()<100);
  await viewport.evaluate(el=>el.scrollTop=0); await ready();
  await page.click('#layout-wrapped-document'); await ready();
  await page.waitForFunction(()=>document.querySelector('.primary [data-line="0"]').getBoundingClientRect().height>32);
  await page.click('#layout-uniform');
  await page.locator('.primary .mk-proportional-run').waitFor({state:'detached'});
  assert.deepEqual(errors,[]);
  console.log('PASS: measured source runs use indexed heights, bounded virtualization and Workspace editing/undo');
} finally {await browser.close();}
