import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage();
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const input = () => page.locator(".language .mk-editor-core-input-sink");
const menu = () => page.locator(".language .mk-native-completions");
const waitText = text => page.waitForFunction(text => document.querySelector(".language-canonical")?.textContent === text, text);
try {
  await page.goto(`http://127.0.0.1:${process.env.PORT ?? "8099"}/`, { waitUntil: "networkidle" });
  await page.click("#wiki-code");
  await page.click("#wiki");
  const resolved = page.locator(".language .mk-native-wiki-resolved");
  await resolved.first().waitFor();
  if ((await resolved.allTextContents()).join("") !== "[[Note é#Heading|alias]]") throw Error("Unicode link offsets are wrong");
  if ((await page.locator(".language .mk-native-wiki-unresolved").allTextContents()).join("") !== "[[Missing]]") throw Error("Missing link styling is wrong");
  if (await page.locator(".primary [class*=mk-native-wiki-]").count()) throw Error("Wiki behavior leaked into Rust");
  await input().focus();
  await page.keyboard.press("Control+Home");
  await page.keyboard.insertText("🔥");
  await waitText("🔥😀中 [[Note é#Heading|alias]] [[Missing]]\r\n");
  await resolved.first().waitFor();
  if ((await resolved.allTextContents()).join("") !== "[[Note é#Heading|alias]]") throw Error("Local edit did not remap link marks");
  await page.click("#wiki-index-toggle");
  await resolved.first().waitFor({ state: "detached" });
  await page.click("#wiki-index-toggle");
  await resolved.first().waitFor();
  await resolved.first().click();
  if (await page.locator("#active-key").textContent() !== "nested.md") throw Error("Plain click followed link");
  await resolved.first().click({ modifiers: ["Control"] });
  await page.waitForFunction(() => document.querySelector("#active-key")?.textContent === "Note é.md");
  if (await page.locator("#active-source").textContent() !== "folder:/tmp/native-fixture") throw Error("Resolved link opened from the wrong folder");
  console.log("ok: Unicode marks, unresolved styling, index refresh and modifier navigation");
  await page.click("#wiki-completion");
  await input().focus();
  await page.keyboard.press("Control+Home");
  await page.keyboard.press("End");
  await page.keyboard.press("ArrowLeft");
  await page.keyboard.press("ArrowLeft");
  await page.keyboard.press("Control+Space");
  await menu().waitFor();
  await page.keyboard.press("Enter");
  await waitText("😀 [[Note é]]\r\n");
  await page.keyboard.press("Control+z");
  await waitText("😀 [[No]]\r\n");
  await page.keyboard.press("Control+Home");
  await page.keyboard.press("Control+End");
  await page.keyboard.type("[[");
  await menu().waitFor();
  await page.keyboard.press("Enter");
  await waitText("😀 [[No]]\r\n[[Note é]]");
  console.log("ok: completion without LSP, typed [[ trigger, no duplicate brackets and atomic undo");
  await page.click("#wiki-completion");
  await page.click("#wiki-delay");
  await input().focus();
  await page.keyboard.press("Control+Home");
  await page.keyboard.press("End");
  await page.keyboard.press("ArrowLeft");
  await page.keyboard.press("ArrowLeft");
  await page.keyboard.press("Control+Space");
  await page.waitForTimeout(250);
  await page.keyboard.press("ArrowLeft");
  await page.click("#wiki-release");
  await page.waitForTimeout(350);
  if (await menu().count()) throw Error("Stale completion reopened after cursor movement");
  await page.click("#wiki");
  await resolved.first().waitFor();
  await page.click("#wiki-delay");
  await resolved.first().click({ modifiers: ["Control"] });
  await page.click("#wiki-completion");
  await page.click("#wiki-release");
  await page.waitForTimeout(400);
  if (await page.locator("#active-key").textContent() !== "nested.md") throw Error("Stale navigation changed the active file");
  await page.click("#wiki");
  await resolved.first().waitFor();
  await page.locator(".language .mk-native-wiki-unresolved").first().click({ modifiers: ["Control"] });
  await page.waitForFunction(() => document.querySelector("#active-key")?.textContent === "Missing.md");
  if (await page.locator("#active-source").textContent() !== "folder:/tmp/native-fixture") throw Error("Missing link created in the wrong folder");
  console.log("ok: source identity, stale navigation cancellation and missing-page creation");
  if (errors.length) throw Error(errors.join("\n"));
  console.log("ok: delayed candidate lookup cannot reopen a stale menu");
} finally {
  await browser.close();
}
