// Deterministic LSP transport, exercised through the production Rust editor.
import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage();
page.setDefaultTimeout(15000);
const errors = [];
page.on("pageerror", error => errors.push(error.message));
const root = page.locator(".primary [data-editor=rust]");
const messages = () => root.locator(".mk-native-diagnostic-message");
const log = async () => JSON.parse(await page.locator(".lsp-log").textContent()).map(JSON.parse);
const count = async method => (await log()).filter(entry => entry.method === method && entry.params?.textDocument?.uri?.endsWith("main.rs")).length;
const waitMethod = async (method, expected) => page.waitForFunction(({method,expected}) => JSON.parse(document.querySelector(".lsp-log").textContent).map(JSON.parse).filter(entry => entry.method === method && entry.params?.textDocument?.uri?.endsWith("main.rs")).length === expected, {method,expected});
try {
  await page.goto(`http://127.0.0.1:${process.env.PORT ?? "8098"}/`);
  await root.waitFor();
  await waitMethod("textDocument/didOpen", 1);
  await page.click("#diagnostics");
  await messages().first().waitFor();
  if (await messages().count() !== 2) throw Error("Missing diagnostics");
  if (await root.locator(".mk-editor-core-cell.mk-native-diagnostic-error").allTextContents().then(values => values.join("")) !== "😀") throw Error("UTF-16 diagnostic did not mark the emoji");
  if (await root.locator(".mk-native-diagnostic-marker").count() !== 2) throw Error("Missing empty-range gutter marker");
  if (!(await messages().first().textContent()).includes("<safe>")) throw Error("Diagnostic message was not escaped as text");
  await messages().last().click();
  await page.waitForFunction(() => document.querySelector(".primary .mk-crust")?.dataset.selectionAnchor === "31");
  await page.click("#diagnostics-clear");
  await messages().first().waitFor({state:"detached"});
  await page.click("#diagnostics");
  await messages().first().waitFor();
  await page.click("#duplicate");
  await page.locator(".duplicate .mk-native-diagnostic-message").first().waitFor();
  if (await count("textDocument/didOpen") !== 1) throw Error("Duplicate view opened document twice");
  await page.click("#mount");
  if (await count("textDocument/didClose") !== 0) throw Error("Unmount closed a document still viewed elsewhere");
  await page.click("#duplicate");
  await waitMethod("textDocument/didClose", 1);
  await page.click("#mount");
  await waitMethod("textDocument/didOpen", 2);
  if (await messages().count()) throw Error("Remount retained closed diagnostics");
  await page.click("#diagnostics");
  await messages().first().waitFor();
  await root.locator(".mk-editor-core-input-sink").focus();
  await page.keyboard.press("Control+End");
  await page.keyboard.type("x");
  await waitMethod("textDocument/didChange", 1);
  await messages().first().waitFor({state:"detached"});
  await page.click("#diagnostics");
  await page.waitForTimeout(100);
  if (await messages().count()) throw Error("Stale version diagnostics accepted");
  await page.click("#diagnostics-current");
  await messages().first().waitFor();
  await page.click("#undo");
  await waitMethod("textDocument/didChange", 2);
  await messages().first().waitFor({state:"detached"});
  await root.locator(".mk-editor-core-input-sink").focus();
  await page.keyboard.press("Control+End"); await page.keyboard.type("y");
  await waitMethod("textDocument/didChange", 3);
  await page.keyboard.press("Control+s");
  await waitMethod("textDocument/didSave", 1);
  const changes = (await log()).filter(entry => entry.method === "textDocument/didChange");
  if (changes.map(entry => entry.params.textDocument.version).join(",") !== "2,3,4") throw Error("Document versions did not advance through edit and undo");
  if (errors.length) throw Error(errors.join("\n"));
  console.log("ok: diagnostics, Unicode ranges, clearing, stale versions, duplicate/remount lifecycle, edits, undo, save");
} finally { await browser.close(); }
